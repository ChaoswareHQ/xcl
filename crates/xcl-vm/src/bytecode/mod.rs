/// One step of an `OP_SELF_UPDATE_CHAIN`: `$self.f = $self.f <op> x`.
#[derive(Debug, Clone, Copy)]
pub struct FieldStep {
    /// Interned destination field name.
    pub key: crate::runtime::value::Value,
    /// Interned source field name, used when `kind == 2`.
    pub rhs_key: crate::runtime::value::Value,
    /// `field_op::{ADD, SUB, MUL}`.
    pub op: u8,
    /// Where the right-hand side comes from: `0` constant in `operand`,
    /// `1` local slot, `2` the field named by `rhs_key`.
    pub kind: u8,
    /// The constant or the local slot, read according to `kind`.
    pub operand: u32,
}

/// A run of consecutive `$self` field updates collapsed into one dispatch.
///
/// The steps live outside the instruction stream because a single 64-bit
/// instruction cannot name two fields, an operator, and an operand. Executing
/// them in one handler removes one dispatch per update without changing what
/// each update does.
#[derive(Debug, Clone)]
pub struct FieldChain {
    /// Updates applied in order to the receiver.
    pub steps: Box<[FieldStep]>,
}

/// Compiled XCL bytecode unit ready for execution by the VM runtime.
///
/// Stores immutable instruction sequences, constant tables, interned identifier strings,
/// and function metadata.
#[derive(Debug, Clone)]
pub struct Bytecode {
    /// Linear sequence of compiled 64-bit bytecode instructions.
    pub instructions: Arc<[Instr]>,
    /// Table of 64-bit wide numeric operands (large integers and IEEE-754 floats).
    pub wide_operands: Arc<[i64]>,
    /// Interned string literals and member/method names.
    pub string_table: Arc<[Box<str>]>,
    /// Pre-allocated string [`Value`](crate::runtime::value::Value) constants corresponding to `string_table`.
    pub string_values: Arc<[crate::runtime::value::Value]>,
    /// Local variable names mapped to slot indices.
    pub local_names: Arc<[Box<str>]>,
    /// Global variable names mapped to slot indices.
    pub global_names: Arc<[Box<str>]>,
    /// User-defined top-level function declarations.
    ///
    /// `Arc` so cloning a `Bytecode` (done once per `run`) is a refcount bump
    /// instead of a deep copy of every function's name and parameters.
    pub user_functions: Arc<[(Box<str>, Arc<crate::runtime::value::FuncValue>)]>,
    /// Callee lookup: `function_by_name[string_index]` is `ordinal + 1` when
    /// that interned string names a user function, `0` otherwise.
    ///
    /// Call instructions already carry the string-table index in operand `b`, so
    /// a named call can find its function with one array load instead of a
    /// `global_index` hash and without inserting function names into that map on
    /// every `run`.
    pub function_by_name: Arc<[u32]>,
    /// Compiled nested closures and lambda bodies.
    pub closures: Arc<[crate::runtime::value::FuncValue]>,
    /// Fused `$self` field-update chains, indexed by `OP_SELF_UPDATE_CHAIN`.
    pub field_chains: Arc<[FieldChain]>,
}
